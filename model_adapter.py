"""
Adaptive Long-Term Memory for Language Models
Phase 3: Model Adapter for Local Qwen GGUF Inference

Supports:
- BaseLLMAdapter: Abstract interface
- LlamaCppAdapter: Local GGUF inference via llama-cpp-python
- FakeLLMAdapter: Deterministic mock adapter for unit/automated testing
"""

from __future__ import annotations

import os
from abc import ABC, abstractmethod
from typing import Any, Callable, Dict, List, Optional


class BaseLLMAdapter(ABC):
    """Abstract interface for LLM response generation."""

    @abstractmethod
    def generate(
        self,
        prompt: str,
        max_tokens: int = 128,
        temperature: float = 0.7,
        **kwargs: Any
    ) -> str:
        """Generate response text given a raw prompt string."""
        pass

    @abstractmethod
    def generate_chat(
        self,
        messages: List[Dict[str, str]],
        max_tokens: int = 128,
        temperature: float = 0.7,
        **kwargs: Any
    ) -> str:
        """Generate response text given chat messages [{"role": ..., "content": ...}]."""
        pass


class FakeLLMAdapter(BaseLLMAdapter):
    """
    Mock LLM adapter for automated unit testing.
    Does not load any weights or require external libraries.
    """

    def __init__(
        self,
        canned_response: Optional[str] = None,
        response_fn: Optional[Callable[[str], str]] = None
    ):
        self.canned_response = canned_response
        self.response_fn = response_fn
        self.call_history: List[Dict[str, Any]] = []

    def generate(
        self,
        prompt: str,
        max_tokens: int = 128,
        temperature: float = 0.7,
        **kwargs: Any
    ) -> str:
        self.call_history.append({"prompt": prompt, "max_tokens": max_tokens})
        if self.response_fn:
            return self.response_fn(prompt)
        if self.canned_response:
            return self.canned_response

        # Default heuristic mock answering based on memory context in prompt
        prompt_lower = prompt.lower()
        if "deepmind" in prompt_lower and ("work" in prompt_lower or "company" in prompt_lower or "employer" in prompt_lower):
            if "previously" in prompt_lower or "before" in prompt_lower or "old" in prompt_lower:
                return "You previously worked at OpenAI before moving to DeepMind."
            return "You currently work at DeepMind."
        if "openai" in prompt_lower and ("previously" in prompt_lower or "before" in prompt_lower):
            return "Based on your memory records, you previously worked at OpenAI."
        if "pytorch" in prompt_lower:
            return "You prefer using PyTorch for your work."
        if "python" in prompt_lower and "dataclass" in prompt_lower:
            return "You prefer concise Python code using dataclasses without boilerplate."

        return "This is a simulated response generated by FakeLLMAdapter."

    def generate_chat(
        self,
        messages: List[Dict[str, str]],
        max_tokens: int = 128,
        temperature: float = 0.7,
        **kwargs: Any
    ) -> str:
        combined = "\n".join(f"{m.get('role', 'user')}: {m.get('content', '')}" for m in messages)
        return self.generate(combined, max_tokens=max_tokens, temperature=temperature, **kwargs)


class LlamaCppAdapter(BaseLLMAdapter):
    """
    Adapter for local Qwen GGUF model using llama-cpp-python.
    Model path is dynamically configured via constructor or environment variable QWEN_MODEL_PATH.
    Never hardcodes machine-specific paths.
    """

    def __init__(
        self,
        model_path: Optional[str] = None,
        n_ctx: int = 2048,
        n_threads: Optional[int] = None,
        temperature: float = 0.7,
        verbose: bool = False
    ):
        resolved_path = model_path or os.environ.get("QWEN_MODEL_PATH")
        if not resolved_path:
            raise ValueError(
                "Model path not specified. Provide 'model_path' parameter or set "
                "the 'QWEN_MODEL_PATH' environment variable."
            )
        if not os.path.exists(resolved_path):
            raise FileNotFoundError(f"Configured Qwen model file does not exist: {resolved_path}")

        self.model_path = resolved_path
        self.n_ctx = n_ctx
        self.default_temperature = temperature
        self.verbose = verbose

        try:
            import llama_cpp
        except ImportError as e:
            raise ImportError(
                "The 'llama-cpp-python' package is required to run LlamaCppAdapter. "
                "Install it via 'pip install llama-cpp-python'."
            ) from e

        # Initialize local Llama model
        kwargs: Dict[str, Any] = {"model_path": self.model_path, "n_ctx": self.n_ctx, "verbose": self.verbose}
        if n_threads:
            kwargs["n_threads"] = n_threads

        self.llm = llama_cpp.Llama(**kwargs)

    def generate(
        self,
        prompt: str,
        max_tokens: int = 128,
        temperature: Optional[float] = None,
        **kwargs: Any
    ) -> str:
        temp = temperature if temperature is not None else self.default_temperature
        response = self.llm(
            prompt=prompt,
            max_tokens=max_tokens,
            temperature=temp,
            **kwargs
        )
        return response["choices"][0]["text"].strip()

    def generate_chat(
        self,
        messages: List[Dict[str, str]],
        max_tokens: int = 128,
        temperature: Optional[float] = None,
        **kwargs: Any
    ) -> str:
        temp = temperature if temperature is not None else self.default_temperature
        response = self.llm.create_chat_completion(
            messages=messages,
            max_tokens=max_tokens,
            temperature=temp,
            **kwargs
        )
        return response["choices"][0]["message"]["content"].strip()
