"""
Adaptive Long-Term Memory for Language Models
Phase 3/4: Model Adapter for Local Qwen GGUF Inference & Token Accounting

Supports:
- BaseLLMAdapter: Abstract interface with tokenization and chat generation
- LlamaCppAdapter: Local GGUF inference via llama-cpp-python using native Qwen tokenizer
- FakeLLMAdapter: Deterministic mock adapter for unit/automated testing
"""

from __future__ import annotations

import math
import os
import re
from abc import ABC, abstractmethod
from typing import Any, Callable, Dict, List, Optional


def heuristic_bpe_token_count(text: str) -> int:
    """
    Tokenizer-compatible subword token estimation when native tokenizer is not loaded.
    Documented limitations: Approximates Byte-Pair Encoding (BPE) for Qwen/GPT models.
    Produces ~1.3 tokens per word, plus adjustments for code/punctuation symbols.
    Never described as exact.
    """
    if not text:
        return 0
    words = text.strip().split()
    # Punctuation and subword heuristic
    punct_count = len(re.findall(r"[^\w\s]", text))
    return max(1, math.ceil(len(words) * 1.3) + math.ceil(punct_count * 0.5))


class BaseLLMAdapter(ABC):
    """Abstract interface for LLM response generation and exact token accounting."""

    name: str = "base"
    is_native_tokenizer: bool = False

    @abstractmethod
    def generate(
        self,
        prompt: str,
        max_tokens: int = 128,
        temperature: float = 0.7,
        **kwargs: Any
    ) -> str:
        """Generate response text given a raw prompt string."""
        pass

    @abstractmethod
    def generate_chat(
        self,
        messages: List[Dict[str, str]],
        max_tokens: int = 128,
        temperature: float = 0.7,
        **kwargs: Any
    ) -> str:
        """Generate response text given chat messages [{"role": ..., "content": ...}]."""
        pass

    @abstractmethod
    def tokenize(self, text: str) -> List[int]:
        """Convert text into token IDs."""
        pass

    def count_tokens(self, text: str) -> int:
        """Count tokens in text."""
        return len(self.tokenize(text))

    def count_chat_tokens(self, messages: List[Dict[str, str]]) -> int:
        """
        Count total tokens formatted in the chat template.
        Includes role markers (<|im_start|>role\ncontent<|im_end|>\n).
        """
        total = 0
        for m in messages:
            # Overhead for Qwen ChatML formatting: ~4 tokens per turn (<|im_start|>role\n ... <|im_end|>\n)
            turn_text = f"<|im_start|>{m.get('role', 'user')}\n{m.get('content', '')}<|im_end|>\n"
            total += self.count_tokens(turn_text)
        return total + 3  # +3 tokens for assistant generation prompt prefix


class FakeLLMAdapter(BaseLLMAdapter):
    """
    Mock LLM adapter for automated unit testing.
    Does not load any weights or require external libraries.
    """

    name: str = "fake"
    is_native_tokenizer: bool = False

    def __init__(
        self,
        canned_response: Optional[str] = None,
        response_fn: Optional[Callable[[str], str]] = None
    ):
        self.canned_response = canned_response
        self.response_fn = response_fn
        self.call_history: List[Dict[str, Any]] = []

    def tokenize(self, text: str) -> List[int]:
        # Deterministic surrogate tokenization for tests
        if not text:
            return []
        tokens = []
        for word in re.findall(r"\w+|[^\w\s]", text):
            tokens.append(abs(hash(word)) % 100000)
        return tokens

    def generate(
        self,
        prompt: str,
        max_tokens: int = 128,
        temperature: float = 0.7,
        **kwargs: Any
    ) -> str:
        self.call_history.append({"prompt": prompt, "max_tokens": max_tokens})
        if self.response_fn:
            return self.response_fn(prompt)
        if self.canned_response:
            return self.canned_response

        prompt_lower = prompt.lower()
        if "deepmind" in prompt_lower and ("work" in prompt_lower or "company" in prompt_lower or "employer" in prompt_lower):
            if "previously" in prompt_lower or "before" in prompt_lower or "old" in prompt_lower:
                return "You previously worked at OpenAI before moving to DeepMind."
            return "You currently work at DeepMind."
        if "openai" in prompt_lower and ("previously" in prompt_lower or "before" in prompt_lower):
            return "Based on your memory records, you previously worked at OpenAI."
        if "pytorch" in prompt_lower:
            return "You prefer using PyTorch for your work."
        if "python" in prompt_lower and "dataclass" in prompt_lower:
            return "You prefer concise Python code using dataclasses without boilerplate."

        return "This is a simulated response generated by FakeLLMAdapter."

    def generate_chat(
        self,
        messages: List[Dict[str, str]],
        max_tokens: int = 128,
        temperature: float = 0.7,
        **kwargs: Any
    ) -> str:
        combined = "\n".join(f"{m.get('role', 'user')}: {m.get('content', '')}" for m in messages)
        return self.generate(combined, max_tokens=max_tokens, temperature=temperature, **kwargs)


class LlamaCppAdapter(BaseLLMAdapter):
    """
    Adapter for local Qwen GGUF model using llama-cpp-python.
    Model path is dynamically configured via constructor or environment variable QWEN_MODEL_PATH.
    Never hardcodes machine-specific paths.
    """

    name: str = "qwen"
    is_native_tokenizer: bool = True

    def __init__(
        self,
        model_path: Optional[str] = None,
        n_ctx: int = 2048,
        n_threads: Optional[int] = None,
        temperature: float = 0.7,
        verbose: bool = False
    ):
        resolved_path = model_path or os.environ.get("QWEN_MODEL_PATH")
        if not resolved_path:
            raise ValueError(
                "Model path not specified. Provide 'model_path' parameter or set "
                "the 'QWEN_MODEL_PATH' environment variable."
            )
        if not os.path.exists(resolved_path):
            raise FileNotFoundError(f"Configured Qwen model file does not exist: {resolved_path}")

        self.model_path = resolved_path
        self.n_ctx = n_ctx
        self.default_temperature = temperature
        self.verbose = verbose

        try:
            import llama_cpp
        except ImportError as e:
            raise ImportError(
                "The 'llama-cpp-python' package is required to run LlamaCppAdapter. "
                "Install it via 'pip install llama-cpp-python'."
            ) from e

        kwargs: Dict[str, Any] = {"model_path": self.model_path, "n_ctx": self.n_ctx, "verbose": self.verbose}
        if n_threads:
            kwargs["n_threads"] = n_threads

        self.llm = llama_cpp.Llama(**kwargs)

    def tokenize(self, text: str) -> List[int]:
        """Uses Qwen's native GGUF embedded tokenizer."""
        return self.llm.tokenize(text.encode("utf-8"))

    def generate(
        self,
        prompt: str,
        max_tokens: int = 128,
        temperature: Optional[float] = None,
        **kwargs: Any
    ) -> str:
        temp = temperature if temperature is not None else self.default_temperature
        response = self.llm(
            prompt=prompt,
            max_tokens=max_tokens,
            temperature=temp,
            **kwargs
        )
        return response["choices"][0]["text"].strip()

    def generate_chat(
        self,
        messages: List[Dict[str, str]],
        max_tokens: int = 128,
        temperature: Optional[float] = None,
        **kwargs: Any
    ) -> str:
        temp = temperature if temperature is not None else self.default_temperature
        response = self.llm.create_chat_completion(
            messages=messages,
            max_tokens=max_tokens,
            temperature=temp,
            **kwargs
        )
        return response["choices"][0]["message"]["content"].strip()


def get_model_adapter(
    model_name: str = "fake",
    model_path: Optional[str] = None,
    n_ctx: int = 2048,
    temperature: float = 0.7,
    verbose: bool = False,
    **kwargs: Any
) -> BaseLLMAdapter:
    """
    Factory to initialize a validated model adapter.
    Guarantees:
    - Explicit backend selection: 'fake' or 'qwen'.
    - Never silently substitutes FakeLLMAdapter when 'qwen' is requested.
    - Explicitly validates model file existence and raises actionable errors.
    """
    choice = model_name.lower().strip()
    if choice == "fake":
        return FakeLLMAdapter(**kwargs)
    elif choice in ("qwen", "llamacpp", "local"):
        resolved_path = model_path or os.environ.get("QWEN_MODEL_PATH")
        if not resolved_path:
            raise ValueError(
                "Qwen model path not specified. Please provide --model-path or set the QWEN_MODEL_PATH environment variable."
            )
        if not os.path.exists(resolved_path):
            raise FileNotFoundError(
                f"Configured Qwen GGUF model file not found at: '{resolved_path}'. "
                f"Please ensure the file exists or check path."
            )
        return LlamaCppAdapter(
            model_path=resolved_path,
            n_ctx=n_ctx,
            temperature=temperature,
            verbose=verbose,
            **kwargs
        )
    else:
        raise ValueError(f"Unsupported model backend '{model_name}'. Choose 'fake' or 'qwen'.")
